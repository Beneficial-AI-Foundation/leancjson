#!/usr/bin/env python3
"""Regenerate CJson/Audit.lean: one `#guard_msgs in #print axioms` per spec.

Run from the project root after `lake build CJson` (use ./audit.sh).
Fails if any spec depends on an axiom other than propext, Classical.choice, Quot.sound.
"""
import re, subprocess, sys, tempfile, os

ALLOWED = {"propext", "Classical.choice", "Quot.sound"}
FILES = ["CJson/Spec.lean", "CJson/SpecExamples.lean"]

names = []
for f in FILES:
    for line in open(f, encoding="utf-8"):
        m = re.match(r"theorem\s+([A-Za-z0-9_']+)", line)
        if m:
            names.append((f, m.group(1)))

probe = "import CJson.Spec\nimport CJson.SpecExamples\nopen CJson.Spec\n" + "".join(
    f"#print axioms {n}\n" for _, n in names)
with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False, dir=".") as t:
    t.write(probe)
    tmp = t.name
try:
    out = subprocess.run(["lake", "env", "lean", tmp], capture_output=True, text=True).stdout
finally:
    os.unlink(tmp)

msgs = re.findall(r"'CJson\.Spec\.([^']+)' (does not depend on any axioms|depends on axioms: \[([^\]]*)\])",
                  out.replace("\n", " "))
got = {m[0]: m for m in msgs}
bad = False
body = []
for f, n in names:
    if n not in got:
        print(f"audit: no axiom report for {n}", file=sys.stderr); bad = True; continue
    _, text, axs = got[n]
    used = {a.strip() for a in axs.split(",") if a.strip()}
    if not used <= ALLOWED:
        print(f"audit: {n} uses forbidden axioms {sorted(used - ALLOWED)}", file=sys.stderr); bad = True
    text = re.sub(r"\s+", " ", text)
    body.append(f"/-- info: 'CJson.Spec.{n}' {text} -/\n#guard_msgs in #print axioms {n}\n")
if bad:
    sys.exit(1)

with open("CJson/Audit.lean", "w", encoding="utf-8") as o:
    o.write('''import CJson.Spec
import CJson.SpecExamples

/-!
# Axiom audit

GENERATED by `./audit.sh` — do not edit; rerun it after adding or changing a spec.
Every theorem of `CJson/Spec.lean` and `CJson/SpecExamples.lean` is listed with the axioms
it depends on. The build fails if a spec starts depending on `sorry` or on anything other
than Lean's three standard axioms (`propext`, `Classical.choice`, `Quot.sound`).
-/

open CJson.Spec

''')
    o.write("\n".join(body))
print(f"audit: {len(body)} specs, all within {sorted(ALLOWED)}")
