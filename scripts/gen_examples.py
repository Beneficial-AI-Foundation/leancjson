#!/usr/bin/env python3
"""Generate CJson/SpecExamples.lean from cJSON's tests/inputs directory.

usage: python3 -I scripts/gen_examples.py /path/to/cJSON/tests/inputs > CJson/SpecExamples.lean
"""
import os, sys

def lit(data: bytes) -> str:
    ok = all(32 <= b < 127 or b in (9, 10, 13) for b in data)
    if not ok:
        return "([" + ", ".join(str(b) for b in data) + "] : Bytes)"
    out = []
    for b in data:
        c = chr(b)
        out.append({"\\": "\\\\", '"': '\\"', "\n": "\\n", "\t": "\\t", "\r": "\\r"}.get(c, c))
    return 'b!"' + "".join(out) + '"'

d = sys.argv[1]
print('''import CJson.Print
import CJson.Parse

/-!
# cJSON example files  (was: `parse_examples.c`)

GENERATED by `scripts/gen_examples.py` from cJSON's `tests/inputs/` (MIT licensed, see
LICENSE) — do not edit. For each `testN` the C test parses the file, prints it with
`cJSON_Print` and compares with `testN.expected`; here that is a kernel-checked theorem.
-/

namespace CJson.Spec
open CJson
''')
for n in [1, 2, 3, 4, 5, 7, 8, 9, 10, 11]:
    i = open(os.path.join(d, f"test{n}"), "rb").read()
    e = open(os.path.join(d, f"test{n}.expected"), "rb").read()
    print(f"/-- file_test{n}_should_be_parsed_and_printed -/")
    print(f"theorem example_test{n} :\n    (parse ({lit(i)})).map print =\n      some ({lit(e)}) := by\n  decide +kernel\n")
i = open(os.path.join(d, "test6"), "rb").read()
print("/-- file_test6_should_not_be_parsed (it is HTML) -/")
print(f"theorem example_test6 :\n    parse ({lit(i)}) = none := by\n  decide +kernel\n")
print("end CJson.Spec")
